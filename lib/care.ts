/**
 * Stepped care ตามโซนสี — ระบบนี้เป็นการดูแลระยะแรก + คัดกรอง + ส่งต่อ ไม่ใช่การรักษา
 *
 *   ยังรับมือเองได้ (calm)     → กิจกรรมดูแลตัวเองสั้น ๆ
 *   เริ่มหนักขึ้น (watch)       → เข้าคิวให้ครูแนะแนวเช็กอินในโรงเรียน
 *   ควรมีคนช่วยดู (care)      → ส่งต่อผู้เชี่ยวชาญ + warm handoff เต็มรูปแบบ
 *   8Q ถึงเกณฑ์ฉุกเฉิน         → เส้นทางฉุกเฉิน ไม่ใช่เรื่องคิว
 *
 * ขั้นคำนวณจากคะแนนที่โค้ดคิดแล้วเท่านั้น (risk / crisis / provisional) ไม่มี AI ตัดสิน
 * ไฟล์นี้ไม่ import อะไร เพื่อให้ทั้ง server, client และ unit test ใช้ได้ตรง ๆ
 */

export type CareStep = "crisis" | "refer" | "checkin" | "self" | "unknown";

/** เรียงตามความเร่งด่วน — ใช้จัดลำดับคิวบนแดชบอร์ดครู */
export const CARE_ORDER: CareStep[] = ["crisis", "refer", "checkin", "self", "unknown"];

export function careStep(c: { risk: "low" | "medium" | "high"; crisis: boolean; provisional: boolean }): CareStep {
  if (c.crisis) return "crisis";
  if (c.risk === "high") return "refer";
  if (c.risk === "medium") return "checkin";
  // คะแนนต่ำเพราะยังคุยน้อย ไม่ได้แปลว่าไม่มีอะไร — ไม่บอกว่า "ดูแลตัวเองได้" จนกว่าจะมีข้อมูลพอ
  return c.provisional ? "unknown" : "self";
}

