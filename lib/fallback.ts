/** คืนคำตอบของ guardrail ถ้าข้อความล่าสุดเข้าเงื่อนไข — ลำดับในนี้คือลำดับความสำคัญ */
function guard(last: string, said: string): string | null {
  const t = last.toLowerCase();
  const danger = has(t, CRISIS);
  if (has(t, IMMINENT) || (has(t, IMMINENT_IN_CONTEXT) && has(said, CRISIS))) return REPLY.imminent;
  if (asksMethod(t)) return REPLY.method;
  if (danger) return REPLY.crisis;

  // ภัยออนไลน์ต้องมาก่อนเรื่อง "ห้ามบอกใคร" เพราะมิจฉาชีพมักเป็นฝ่ายสั่งให้เงียบ
  const domains = detectDomains(t).filter((d) => d.confidence >= DOMAIN_FLOOR).map((d) => d.id);
  if (has(t, MULE)) return REPLY.mule;
  if (domains.includes("online_threat")) return REPLY.online;
  if (domains.includes("family_violence")) return REPLY.family;

  if (has(t, ROMANCE)) return REPLY.romance;
  if (has(t, IDENTITY)) return REPLY.identity;
  if (has(t, SECRECY)) return REPLY.secrecy;
  if (has(t, DIAGNOSE)) return REPLY.diagnose;
  return null;
}

