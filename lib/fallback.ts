const CLOSING =
  "เราคุยกันมาพอสมควรแล้ว ขอสรุปให้ดูได้ไหมว่าตอนนี้อยู่ระดับไหน แล้วเธอเป็นคนเลือกเองว่าจะทำอะไรต่อ";

function pick<T>(arr: T[], seed: number) {
  return arr[seed % arr.length];
}

function topicOf(text: string) {
  return TOPICS.find((t) => t.keys.some((k) => text.includes(k)));
}

export function fallbackReply(messages: Msg[]): string {
  const users = messages.filter((m) => m.role === "user");
  const last = users[users.length - 1]?.content ?? "";
  const said = users.map((m) => m.content).join(" ");
  const n = users.length;

  const guarded = guard(last, said);
  if (guarded) return guarded;

  const hit = topicOf(last);

  // หัวข้อที่ยังไม่ได้แตะเลย
  const covered = new Set(
    QUEUE.filter((q) => TOPICS.find((t) => t.id === q.id)?.keys.some((k) => said.includes(k))).map((q) => q.id)
  );
  const next = QUEUE.find((q) => !covered.has(q.id) && q.id !== hit?.id);

  if (n >= 8 || !next) return CLOSING;

  // ตรงกับหัวข้อ → สะท้อนสิ่งที่เขาพูด แล้วถามลึกลงในเรื่องเดียวกันก่อน
  if (hit) {
    const depth = users.filter((m) => topicOf(m.content)?.id === hit.id).length;
    if (depth <= 2) return `${pick(hit.reflect, n)}\n\n${pick(hit.probe, depth - 1 < 0 ? 0 : depth - 1)}`;
    return `${pick(hit.reflect, n)}\n\n${next.q}`;
  }

  // ไม่ตรงหัวข้อไหนเลย — รับรู้สั้น ๆ แล้วค่อยชวนกลับเข้าเรื่อง ไม่ทำเป็นไม่ได้ยิน
  return `${pick(ACK, n)}\n\n${next.q}`;
}
