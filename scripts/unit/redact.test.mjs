test("สัญญาณอันตรายและเนื้อหาที่ใช้ประเมินต้องอยู่ครบหลังตัด", () => {
  const msg = "ผมชื่อธนกฤต อยู่โรงเรียนสวนกุหลาบ ม.5/2 เบอร์ 0812345678 ช่วงนี้อยากตาย นอนไม่หลับ มีคนขู่ว่าจะปล่อยรูป";
  const out = gone(msg, ["ธนกฤต", "สวนกุหลาบ", "0812345678", "5/2"], ["อยากตาย", "นอนไม่หลับ", "ขู่ว่าจะปล่อยรูป"]);
  assert.match(out, /\[ชื่อ\].*\[โรงเรียน\].*\[ห้อง\].*\[เบอร์โทร\]/);
});

