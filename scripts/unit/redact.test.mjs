test("maskKnown: ตัดชื่อและเบอร์ที่กรอกไว้ในโปรไฟล์แบบตรงตัว", () => {
  const known = { names: ["ปัณณ์ วรกุล", "ฟ้า", "สมพร วรกุล"], phones: ["081-234-5678"] };
  const out = maskKnown("ปัณณ์เองนะ หรือเรียกฟ้าก็ได้ แม่สมพรโทรจาก 0812345678 ตอนมองท้องฟ้า", known);
  for (const s of ["ปัณณ์", "สมพร", "0812345678"]) assert.ok(!out.includes(s), out);
  assert.ok(out.includes("ท้องฟ้า"), `ชื่อเล่นสั้นต้องไม่ตัดคำอื่น → ${out}`);
  assert.ok(out.includes(TAG.phone) && out.includes(TAG.name));
  assert.equal(maskKnown("ไม่มีอะไรต้องตัด", known), "ไม่มีอะไรต้องตัด");
  assert.equal(maskKnown("ข้อความเดิม", {}), "ข้อความเดิม");
});

