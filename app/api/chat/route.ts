export async function POST(req: Request) {
  const { messages } = (await req.json()) as { messages: Msg[] };
  const stream = await chatStream(messages, SYSTEM);
  return new Response(stream, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "X-Source": provider(),
    },
  });
}
